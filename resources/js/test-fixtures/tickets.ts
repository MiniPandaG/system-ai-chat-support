/** El elemento de una lista de ejemplo; falla con un mensaje claro si no existe, en vez de devolver undefined. */
export function pick<T>(items: readonly T[], index: number): T {
    const item = items[index];
    if (item === undefined) throw new Error(`Falta el elemento ${String(index)} de los datos de ejemplo.`);

    return item;
}
